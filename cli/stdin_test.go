func TestStdinFixLevelsAndRemainingDiagnostics(t *testing.T) {
	for _, tc := range []struct {
		flag string
		kind goxlint.FixKind
	}{
		{"--fix", goxlint.FixSafe}, {"--fix-suggestions", goxlint.FixSuggestion}, {"--fix-dangerously", goxlint.FixDangerous},
	} {
		t.Run(tc.flag, func(t *testing.T) {
			t.Chdir(t.TempDir())
			writeTestFile(t, ".goxlintrc.json", `{"categories":{"correctness":"error"}}`)
			plugin := goxlint.Plugin{Name: "test", Rules: []*goxlint.Rule{
				expressionFixRule("replace", map[string]string{"1": "2"}, tc.kind),
				{Meta: goxlint.Meta{Name: "remaining", Category: goxlint.Correctness}, Create: func(ctx *goxlint.Context) goxlint.Visitor {
					ctx.Report(goxlint.Diagnostic{Node: ctx.File.Name, Message: "remaining finding"})
					return nil
				}},
			}}
			var stdout, stderr bytes.Buffer
			code := run([]string{"--stdin-filename=new/buffer.go", tc.flag, "--format=unix"}, strings.NewReader("package p\nvar n=1\n"), &stdout, &stderr, plugin)
			if code != 1 || stdout.String() != "package p\nvar n=2\n" || !strings.Contains(stderr.String(), "new/buffer.go:1:9: remaining finding") {
				t.Fatalf("exit %d: %s; %s", code, &stdout, &stderr)
			}
			if _, err := os.Stat("new"); !errors.Is(err, os.ErrNotExist) {
				t.Fatalf("created directory: %v", err)
			}
		})
	}
}
