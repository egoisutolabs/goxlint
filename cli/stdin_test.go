func TestStdinOverlay(t *testing.T) {
	for _, typed := range []bool{false, true} {
		for _, exists := range []bool{false, true} {
			t.Run(fmt.Sprintf("typed=%t/exists=%t", typed, exists), func(t *testing.T) {
				t.Chdir(t.TempDir())
				writeTestFile(t, "go.mod", "module test.local/stdin\n\ngo 1.26.0\n")
				writeTestFile(t, ".goxlintrc.json", `{"rules":{"test/rename":"error"}}`)
				if err := os.MkdirAll("internal/api", 0o755); err != nil {
					t.Fatal(err)
				}
				name := filepath.Join("internal", "api", "buffer_test.go")
				disk := "this is invalid Go on disk\n"
				if exists {
					writeTestFile(t, name, disk)
				}
				writeTestFile(t, filepath.Join("internal", "api", "sibling.go"), "package api\nfunc sibling() { var bad = 1; _ = bad }\n")
				src := "package api\n//line imaginary.go:100\nvar bad = \"buffer\"\n"
				plugin := testPlugin(typed)
				create := plugin.Rules[0].Create
				plugin.Rules[0].Create = func(ctx *goxlint.Context) goxlint.Visitor {
					if filepath.Base(ctx.Filename) == "buffer_test.go" {
						if string(ctx.Source) != src || !ctx.IsTestFile() {
							t.Errorf("wrong buffer context: %s", ctx.Source)
						}
						if typed {
							decl := ctx.File.Decls[0].(*ast.GenDecl).Specs[0].(*ast.ValueSpec)
							if ctx.TypesInfo.TypeOf(decl.Values[0]).String() != "string" {
								t.Error("types did not use the buffer")
							}
						}
					}
					return create(ctx)
				}
				var stdout, stderr bytes.Buffer
				inputName := name
				if exists {
					var err error
					inputName, err = filepath.Abs(name)
					if err != nil {
						t.Fatal(err)
					}
				}
				code := run([]string{"--stdin-filename", inputName, "--format=json"}, strings.NewReader(src), &stdout, &stderr, plugin)
				if code != 1 || stderr.Len() != 0 {
					t.Fatalf("exit %d: %s; %s", code, &stdout, &stderr)
				}
				var diags []struct {
					File         string
					Line, Column int
				}
				if err := json.Unmarshal(stdout.Bytes(), &diags); err != nil {
					t.Fatal(err)
				}
				if len(diags) != 1 || diags[0].File != "internal/api/buffer_test.go" || diags[0].Line != 3 || diags[0].Column != 5 {
					t.Fatalf("wrong buffer diagnostics: %s", &stdout)
				}
				contents, err := os.ReadFile(name)
				if exists && (err != nil || string(contents) != disk) {
					t.Fatalf("disk changed: %q: %v", contents, err)
				}
				if !exists && !errors.Is(err, os.ErrNotExist) {
					t.Fatalf("created buffer on disk: %v", err)
				}
			})
		}
	}
}

func TestStdinConfiguration(t *testing.T) {
	for _, tc := range []struct {
		name, config, source string
		want                 int
	}{
		{"override", `{"rules":{"test/rename":"error"},"overrides":[{"files":["buffer_test.go"],"rules":{"test/rename":"off"}}]}`, "package p\nvar bad = 1\n", 0},
		{"ignore", `{"rules":{"test/rename":"error"},"ignorePatterns":["buffer_test.go"]}`, "not valid Go", 0},
		{"generated", `{"rules":{"test/rename":"error"}}`, "// Code generated by test. DO NOT EDIT.\npackage p\nvar bad = 1\n", 0},
		{"suppressed", `{"rules":{"test/rename":"error"}}`, "package p\n//goxlint:ignore test/rename reason\nvar bad = 1\n", 0},
	} {
		for _, typed := range []bool{false, true} {
			t.Run(fmt.Sprintf("%s/typed=%t", tc.name, typed), func(t *testing.T) {
				t.Chdir(t.TempDir())
				writeTestFile(t, "go.mod", "module test.local/stdin\n\ngo 1.26.0\n")
				writeTestFile(t, ".goxlintrc.json", tc.config)
				writeTestFile(t, "buffer_test.go", "package p\n")
				var stdout, stderr bytes.Buffer
				if code := run([]string{"--stdin-filename=buffer_test.go", "--format=json"}, strings.NewReader(tc.source), &stdout, &stderr, testPlugin(typed)); code != tc.want || stderr.Len() != 0 || strings.TrimSpace(stdout.String()) != "[]" {
					t.Fatalf("exit %d: %s; %s", code, &stdout, &stderr)
				}
			})
		}
	}
}

func TestStdinPackageFixes(t *testing.T) {
	for _, typed := range []bool{false, true} {
		t.Run(fmt.Sprint(typed), func(t *testing.T) {
			t.Chdir(t.TempDir())
			writeTestFile(t, "go.mod", "module test.local/stdin\n\ngo 1.26.0\n")
			writeTestFile(t, ".goxlintrc.json", `{"rules":{"test/package":"error"}}`)
			disk := "package p\n\nvar buffer = 0\n"
			sibling := "package p\n\nvar sibling = 1\n"
			writeTestFile(t, "buffer.go", disk)
			writeTestFile(t, "sibling.go", sibling)
			calls := 0
			rule := &goxlint.Rule{Meta: goxlint.Meta{Name: "package", NeedsTypes: typed, Fixable: goxlint.FixSafe}, AnalyzePackage: func(pkg *goxlint.PackageContext) {
				calls++
				if len(pkg.Files) != 2 {
					t.Errorf("want both package files, got %d", len(pkg.Files))
				}
				for _, file := range pkg.Files {
					ast.Inspect(file.File, func(n ast.Node) bool {
						if lit, ok := n.(*ast.BasicLit); ok && lit.Value == "1" {
							file.Report(goxlint.Diagnostic{Node: lit, Message: "replace one", Fix: &goxlint.Fix{Kind: goxlint.FixSafe, Edits: []goxlint.Edit{goxlint.ReplaceNode(lit, "2+3")}}})
						}
						return true
					})
				}
			}}
			var stdout, stderr bytes.Buffer
			code := run([]string{"--stdin-filename=buffer.go", "--fix", "--format=json", "--timing"}, strings.NewReader("package p\n\nvar buffer = 1\n"), &stdout, &stderr, goxlint.Plugin{Name: "test", Rules: []*goxlint.Rule{rule}})
			if code != 0 || calls != 3 || stdout.String() != "package p\n\nvar buffer = 2 + 3\n" {
				t.Fatalf("exit %d, calls %d: %s; %s", code, calls, &stdout, &stderr)
			}
			if !strings.Contains(stderr.String(), "Applied 1 fix(es) in 1 pass(es).\n[]") || !strings.Contains(stderr.String(), "Load (") {
				t.Fatalf("missing diagnostics or timing: %s", &stderr)
			}
			for name, want := range map[string]string{"buffer.go": disk, "sibling.go": sibling} {
				got, err := os.ReadFile(name)
				if err != nil || string(got) != want {
					t.Fatalf("changed %s: %q: %v", name, got, err)
				}
			}
		})
	}
}

func TestStdinFixOutput(t *testing.T) {
	for _, tc := range []struct {
		name, source, want, config, replacement string
		code                                    int
	}{
		{"raw formatting", "package p\nvar value=1\n", "package p\nvar value=2+3\n", `{}`, "2+3", 0},
		{"no fixes", "package p\nvar value=2\n", "package p\nvar value=2\n", `{}`, "2+3", 0},
		{"ignored", "invalid buffer", "invalid buffer", `{"ignorePatterns":["buffer.go"]}`, "2+3", 0},
		{"parse error", "invalid buffer", "invalid buffer", `{}`, "2+3", 2},
		{"invalid fix", "package p\n\nvar value = 1\n", "package p\n\nvar value = 1\n", `{}`, "(", 2},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Chdir(t.TempDir())
			writeTestFile(t, ".goxlintrc.json", tc.config)
			var stdout, stderr bytes.Buffer
			plugin := goxlint.Plugin{Name: "test", Rules: []*goxlint.Rule{expressionFixRule("replace", map[string]string{"1": tc.replacement}, goxlint.FixSafe)}}
			code := run([]string{"--stdin-filename=buffer.go", "--fix", "-D", "test/replace"}, strings.NewReader(tc.source), &stdout, &stderr, plugin)
			if code != tc.code || stdout.String() != tc.want {
				t.Fatalf("exit %d: source %q; %s", code, &stdout, &stderr)
			}
			if !strings.Contains(stderr.String(), "Found ") {
				t.Fatalf("summary not on stderr: %s", &stderr)
			}
			if _, err := os.Stat("buffer.go"); !errors.Is(err, os.ErrNotExist) {
				t.Fatalf("wrote buffer to disk: %v", err)
			}
		})
	}
}

func TestStdinUsageAndReadErrors(t *testing.T) {
	t.Chdir(t.TempDir())
	writeTestFile(t, ".goxlintrc.json", `{}`)
	for _, args := range [][]string{{"--stdin-filename="}, {"--stdin-filename=buffer.go", "."}, {"--stdin-filename=buffer.go", "--format=invalid"}} {
		var stdout, stderr bytes.Buffer
		code := run(args, forbiddenReader{t}, &stdout, &stderr)
		if code != 2 || stdout.Len() != 0 {
			t.Fatalf("exit %d: %s; %s", code, &stdout, &stderr)
		}
	}
	var stdout, stderr bytes.Buffer
	if code := run([]string{"--stdin-filename=buffer.go"}, errorReader{}, &stdout, &stderr); code != 2 || !strings.Contains(stderr.String(), "read stdin") {
		t.Fatalf("exit %d: %s", code, &stderr)
	}
}

type forbiddenReader struct{ t *testing.T }

func (r forbiddenReader) Read([]byte) (int, error) {
	r.t.Fatal("read stdin for invalid arguments")
	return 0, io.EOF
}

type errorReader struct{}

func (errorReader) Read([]byte) (int, error) { return 0, io.ErrUnexpectedEOF }

